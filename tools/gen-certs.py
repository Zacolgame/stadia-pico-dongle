#!/usr/bin/env python3
"""gen-certs.py -- regenerate src/certs.c HTTPS chain+key from upstream PEMs.

Usage (from repo root): python tools/gen-certs.py
Reads vendor/upstream-credential/{fullchain,privkey,leaf}.pem (LF, LF-terminated),
emits the TLS_CERT_PEM/TLS_KEY_PEM/TLS_LEAF_PEM arrays (bytes + NUL, len incl. NUL
per the mbedtls_x509_crt_parse convention). The DTLS EC arrays are preserved
byte-identical from the existing certs.c. Verifies by re-parsing every emitted
PEM block and comparing SHA-256 against the sources. Non-ASCII-safe (writes bytes).
"""
import hashlib
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, 'vendor', 'upstream-credential')
DTLS_SRC = os.path.join(ROOT, 'vendor', 'selfsigned-dtls')
DST = os.path.join(ROOT, 'src', 'certs.c')


def load(d, name):
    with open(os.path.join(d, name), 'rb') as fh:
        data = fh.read().replace(b'\r\n', b'\n')
    assert data.endswith(b'\n'), name
    return data


def carray(data):
    body = ','.join(str(b) for b in data) + ',0'
    return body


def main():
    regen_dtls = os.path.isdir(DTLS_SRC) and os.path.exists(os.path.join(DTLS_SRC, 'leaf.pem'))
    fullchain = load(SRC, 'fullchain.pem')
    privkey = load(SRC, 'privkey.pem')
    leaf = load(SRC, 'leaf.pem')

    with open(DST, 'rb') as fh:
        old = fh.read().decode('utf-8')

    if regen_dtls:
        # Regenerate the DTLS self-signed arrays from vendor/selfsigned-dtls/.
        ec_cert = load(DTLS_SRC, 'leaf.pem')
        ec_key = load(DTLS_SRC, 'privkey.pem')
        ec_tail = '\n'.join([
            '// DTLS self-signed EC P-256 leaf (minimal, single-datagram flight).',
            '// Regenerated from vendor/selfsigned-dtls/*.pem; see PROVENANCE there.',
            '// The controller pins the leaf fingerprint from SDP and never validates',
            '// this chain, so a throwaway lab identity is correct here by design.',
            'const unsigned char TLS_EC_CERT_PEM[] = {%s};' % carray(ec_cert),
            'const unsigned int TLS_EC_CERT_PEM_len = %d;' % (len(ec_cert) + 1),
            'const unsigned char TLS_EC_KEY_PEM[] = {%s};' % carray(ec_key),
            'const unsigned int TLS_EC_KEY_PEM_len = %d;' % (len(ec_key) + 1),
            '',
        ])
    else:
        # Preserve the DTLS EC arrays verbatim (from TLS_EC_CERT_PEM to EOF).
        m = re.search(r'(// DTLS alternative.*)\Z', old, re.S)
        assert m, 'EC section anchor missing'
        ec_tail = m.group(1)

    out = []
    out.append('// certificate definitions (single TU) - generated by tools/gen-certs.py')
    out.append('// DO NOT EDIT: regenerate from vendor/upstream-credential/*.pem')
    out.append('#include "certs.h"')
    out.append('// HTTPS: full EC chain (stadiacast.lol leaf + WR1 + GTS Root R1).')
    out.append('// The controller validates chain-to-GTS-roots only (no hostname/date/revocation check),')
    out.append('// so this revoked-at-owner-request credential (see vendor/upstream-credential/PROVENANCE.txt)')
    out.append('// is safe to embed and needs no renewing.')
    out.append('const unsigned char TLS_CERT_PEM[] = {%s};' % carray(fullchain))
    out.append('const unsigned int TLS_CERT_PEM_len = %d;' % (len(fullchain) + 1))
    out.append('const unsigned char TLS_KEY_PEM[] = {%s};' % carray(privkey))
    out.append('const unsigned int TLS_KEY_PEM_len = %d;' % (len(privkey) + 1))
    out.append('const unsigned char TLS_LEAF_PEM[] = {%s};' % carray(leaf))
    out.append('const unsigned int TLS_LEAF_PEM_len = %d;' % (len(leaf) + 1))
    out.append('')
    out.append(ec_tail)
    new_text = '\n'.join(out)
    with open(DST, 'wb') as fh:
        fh.write(new_text.encode('utf-8'))

    # Verify: re-parse every PEM block we emitted.
    got = new_text
    expect = [('TLS_CERT_PEM', fullchain), ('TLS_KEY_PEM', privkey),
              ('TLS_LEAF_PEM', leaf)]
    if regen_dtls:
        expect += [('TLS_EC_CERT_PEM', ec_cert), ('TLS_EC_KEY_PEM', ec_key)]
    for name, want in expect:
        mm = re.search(name + r'\[\] = \{([0-9,]+)\}', got)
        assert mm, name
        raw = bytes(int(x) for x in mm.group(1).split(','))
        assert raw.endswith(b'\x00') and raw[:-1] == want, name + ' mismatch'
        h = hashlib.sha256(raw[:-1]).hexdigest()[:16]
        print('%s: %d bytes (+NUL), sha256=%s OK' % (name, len(want), h))
    # EC tail untouched? (compare bytes: text-mode reads translate newlines)
    assert ec_tail.encode('utf-8') in open(DST, 'rb').read(), 'ec tail'
    print(('EC DTLS arrays regenerated from vendor/selfsigned-dtls.'
           if regen_dtls else 'EC DTLS arrays preserved byte-identical.')
          + ' certs.c regenerated.')


if __name__ == '__main__':
    sys.exit(main())
